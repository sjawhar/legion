-- 20261106120000_claim_owed_task.up.sql — the task an update round's question went before
-- (INFRA-956 R2).
--
-- A turn that ends in a provider error keeps its task (20261105004846_provider_error_retry), and
-- the daemon sends it to the same session again on a ladder whose steps reach ten minutes. An
-- update round's question — the daemon asking this claim's worker to push its work, because the
-- pod it runs in is about to be replaced — goes before that task rather than waiting behind it,
-- and it needs the claim's one delivery slot. The task it goes before is still owed, so the
-- daemon held it in the memory of the process that took it off the claim.
--
-- Memory is not enough: the outbox start row that gave that task is recorded on the claim
-- (claims.delivered_rows), so no retry of that row ever gives it again, and the rollout that
-- opens these rounds replaces the daemon's own pod while they run. A daemon restarted while the
-- question was pending read the question off the claim and the task was gone.
--
-- claims.owed_task is that task, as supervise.Delivery encoded in JSON: its id, its text, the
-- phase and run it was queued for, its read mark, and how far up the ladder it already is, so
-- the task comes back exactly as it was taken and its next provider error goes on up the ladder
-- rather than starting a new one. null is a claim that owes no such task, which is every claim
-- outside an update round that interrupted one.
--
-- It is a column of the claim rather than a second row of pending_task_deliveries, because that
-- table holds one row per claim and a held task is not pending: nothing sends it until it is the
-- claim's delivery again. The claim is written in the same transaction as the delivery the hold
-- takes it from is deleted, and as the delivery that gives it back is inserted (the claim
-- store's RetireDelivery and PutClaimAndDelivery), so no commit leaves the task in both places
-- or in neither.
alter table claims add column owed_task jsonb;
