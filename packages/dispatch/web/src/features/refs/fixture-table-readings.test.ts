import { beforeAll, expect, test } from "bun:test";
import type { ParagraphReading } from "@legion/proof-editor/reading";
import { DOMSerializer } from "prosemirror-model";

import { fixture, type PmdocFixture, pmdocFixtures } from "../../__tests__/pmdoc-fixtures";
import {
  footnote,
  html,
  type LeafRow,
  leafMarksInOneDocumentReading,
  listsSpacedByIndentedCodeReading,
  row,
} from "../../__tests__/pmdoc-leaf-readings";
import { loadedEngine, type MarkdownEngine, warmMarkdownRenderer } from "./markdown-engine";

/**
 * What the one fixture table (`__tests__/pmdoc-fixtures.ts`) says each corpus document reads as,
 * proved against a real DOM here, where the browser rows that proved it three times over - once
 * in the spec editor, once in a past version, once in a comment - no longer do.
 *
 * Every assertion below goes through the real pipeline a web surface drives: the shared engine's
 * own `parse`, then ProseMirror's `DOMSerializer` over the parsed document, into the happy-dom
 * document `web/src/__tests__/setup.ts` registers - never an injected DOM, as
 * `MarkdownBody.test.tsx`'s link row says of the same pipeline. The engine is the page's
 * (`markdown-engine.ts`), built from the server's block schema; the table's expectations were
 * generated by the headless engine the generator builds (`pmdoc/gen/gen.ts`), so a difference
 * between the two configurations is a failure here.
 */

let engine: MarkdownEngine;
let serializer: DOMSerializer;

beforeAll(async () => {
  await warmMarkdownRenderer();
  const loaded = loadedEngine();
  if (loaded === undefined) {
    throw new Error("the shared Markdown engine did not load");
  }
  engine = loaded;
  // The serializer `readDocument` uses, the schema's own, not the engine's `pictureSerializer`:
  // the table's readings were drawn through this one.
  serializer = DOMSerializer.fromSchema(loaded.schema);
});

/** `entry`'s markdown parsed by the page's engine and serialized into a detached element of the
 *  test's document, which is what a reader's browser would hold. */
function draw(entry: PmdocFixture): Element {
  const doc = engine.parse(entry.markdown);
  if (doc === undefined) {
    throw new Error(`the engine refused ${entry.name}`);
  }
  const root = document.createElement("div");
  root.appendChild(serializer.serializeFragment(doc.content, { document }));
  return root;
}

/** The text of every `selector` element inside `element`, in document order. */
function texts(element: Element, selector: string): string[] {
  return [...element.querySelectorAll(selector)].map((found) => found.textContent ?? "");
}

/** Each paragraph of `root` as a reading: the text of its `em`, `strong` and `del` elements, and
 *  its own text with runs of whitespace collapsed. */
function paragraphReadings(root: Element): ParagraphReading[] {
  return [...root.querySelectorAll("p")].map((paragraph) => ({
    emphasized: texts(paragraph, "em"),
    strong: texts(paragraph, "strong"),
    struck: texts(paragraph, "del"),
    text: (paragraph.textContent ?? "").replace(/\s+/g, " ").trim(),
  }));
}

/** Each table of `root` as its rows, each row as the text of its `th, td` cells, in document
 *  order. */
function tableRows(root: Element): string[][][] {
  return [...root.querySelectorAll("table")].map((table) =>
    [...table.querySelectorAll("tr")].map((row) => texts(row, "th, td"))
  );
}

/** One document of the table, drawn once and read three ways. */
interface TableReading {
  readonly entry: PmdocFixture;
  readonly leaves: readonly LeafRow[];
  readonly paragraphs: readonly ParagraphReading[];
  readonly tables: readonly string[][][];
}

let tableReadings: TableReading[] | undefined;

/** Every document of the table, drawn once for the file: the two tests below that walk the whole
 *  table read this rather than parsing and serializing all 193 documents each. Only the derived
 *  readings are kept, never the drawn roots - retaining all 193 of those costs about 50 MB
 *  of heap. Filled on first read rather than in a `beforeAll`, so a document the engine refuses
 *  still throws `draw`'s own message from inside whichever test reads first, and the other test
 *  throws it again. */
function wholeTable(): TableReading[] {
  tableReadings ??= pmdocFixtures.map((entry) => {
    const root = draw(entry);
    return {
      entry,
      leaves: leafRows(root),
      paragraphs: paragraphReadings(root),
      tables: tableRows(root),
    };
  });
  return tableReadings;
}

// (a) The reading the table stores for a document - its paragraphs and its tables - is the
// reading a DOM shows for it.
//
// This carries, for every one of the corpus documents, what `expectParagraphReadings`
// (`e2e/editor.ts`) asserted in a browser for the three families whose comparand is a paragraph
// reading: the deleted comment rows of `strikethrough.e2e.ts`, `emphasis-beside-a-tilde.e2e.ts`
// and `writer-spelling.e2e.ts`, whose one surviving row each - a past version for the first
// two, the spec editor for the third - is all that calls that helper now. The paragraph reader
// below is that helper's, line for line - each paragraph's `em`, `strong` and `del` text, and
// the paragraph's own text with runs of whitespace collapsed - and the table reader is
// `document-reading.ts`'s selectors for a table, line for line: every `table` in document
// order, each as its rows, each row as the text of its `th, td` cells. Both are written out
// rather than calling `readDocument`, which reads those same things, because the stored side of
// this comparison was generated by `readDocument`: drawing the other side with it too would
// leave both sides the answer of one function, and this test would stop being an oracle for it.
//
// Twenty-one of the 193 documents hold a table - `table-then-setext-underline` holds eight
// tables, `tables-then-empty-items` six - so the table side of the comparison is not vacuous.
//
// This row draws every one of the 193 documents through the real engine and `DOMSerializer` and
// compares its drawn paragraphs and tables with the reading the table stores, and it is the row
// that fills `wholeTable()` - the one drawing the rows below read - so the file's whole cost
// sits here: 2.02 s, 2.19 s and 2.30 s over three runs on an issue pod's two cores, where it
// passes a `--timeout 2000` and times out at 1900, while the four rows below cost under 25 ms
// each. Bun's 5 s default is only about twice its cost, which one busy core takes: the row red
// once in four runs of `bun run test` at 5,660 ms (INFRA-1404), and with two spinners holding
// both cores here it cost 7.13 s. Thirty seconds leaves room above that and still fails a hung
// row, where sixty would mostly cost run time.
test("every document of the table reads in a DOM as the table says it reads", () => {
  const differing: string[] = [];
  for (const { entry, paragraphs, tables } of wholeTable()) {
    const readings = [
      { drawn: paragraphs, stored: entry.reading.paragraphs, what: "paragraphs" },
      { drawn: tables, stored: entry.reading.tables, what: "tables" },
    ];
    for (const { drawn, stored, what } of readings) {
      if (JSON.stringify(drawn) !== JSON.stringify(stored)) {
        differing.push(
          `${entry.name} ${what}\n  stored: ${JSON.stringify(stored)}\n  drawn:  ${JSON.stringify(drawn)}`
        );
      }
    }
  }
  // Named one by one rather than compared whole: a drift is one corpus document, and a failure
  // that printed all 193 readings would bury it.
  expect(differing).toEqual([]);
}, 30_000);

// (b) The claims `leaf-marks.e2e.ts`'s comment row carried, which no paragraph reading holds: an
// inline leaf - raw HTML, a picture, a footnote reference - carries no text, so no mark may wrap
// it, and the paragraph's text is read uncollapsed, since whitespace is part of this reading
// (`leaf-marks.e2e.ts:26-28`, whose surviving past-version row keeps a reader of its own at
// `:43-75`).

/**
 * Every paragraph of `root`, as its inline leaves and its uncollapsed text. Only the document's
 * own leaves are read: after a paragraph whose last child is a leaf node a live editor appends an
 * `<img class="ProseMirror-separator">` of its own, which is chrome and no leaf of the document,
 * so the e2e reader skips it and so does this one.
 */
function leafRows(root: Element): LeafRow[] {
  return [...root.querySelectorAll("p")].map((paragraph) => ({
    leaves: [
      ...paragraph.querySelectorAll(
        'span[data-type="html"], img:not(.ProseMirror-separator), sup[data-type="footnote_reference"]'
      ),
    ].map((leaf) => {
      const marks: string[] = [];
      for (
        let ancestor = leaf.parentElement;
        ancestor !== null && ancestor !== paragraph;
        ancestor = ancestor.parentElement
      ) {
        const tag = ancestor.tagName.toLowerCase();
        if (tag === "strong" || tag === "em" || tag === "del" || tag === "a") {
          marks.push(tag);
        }
      }
      return {
        identity:
          leaf.getAttribute("data-value") ??
          leaf.getAttribute("src") ??
          leaf.getAttribute("data-label") ??
          "",
        kind: leaf.tagName.toLowerCase(),
        marks,
      };
    }),
    text: paragraph.textContent ?? "",
  }));
}

// The two corpus documents those claims are read over, each a file of
// `packages/envoy/internal/dispatch/pmdoc/testdata/corpus/`: `leaf-marks-in-one-document`, whose
// eight rows `leaf-marks.e2e.ts:35` seeds into a spec and reads back from a past version, and
// `marks-on-addresses-before-inline-html`, whose five address paragraphs no browser row reads.
test("no mark reaches an inline leaf, and a declaration is raw HTML, in the two leaf-mark documents", () => {
  expect(leafRows(draw(fixture("leaf-marks-in-one-document")))).toEqual(
    leafMarksInOneDocumentReading
  );
  expect(leafRows(draw(fixture("marks-on-addresses-before-inline-html")))).toEqual([
    row("(www.a'b@c.test/a~b<b>**", html("<b>")),
    row("www.a!b@c.test/q?a=1&b=2<b> and more", html("<b>")),
    row("**www.api.github.com/ab<b>***"),
    row("(HTTPS://localhost/a`b<b>*`", html("<b>")),
    row("www.api.github.com/q?a=1&b=2<b>", html("<b>")),
  ]);
});

// The same row's other claim, over the corpus document that spells a declaration every way: an
// inline HTML declaration (`<!` and an ASCII letter) is raw HTML, so it is a leaf like any other
// tag; `<!>`, `<!1>`, `<! a>`, an escaped `\<!a>` and one inside a code span are text.
test("every declaration spelling that is raw HTML draws a leaf, and the rest draw text", () => {
  expect(leafRows(draw(fixture("html-declarations")))).toEqual([
    row("p <!a> q", html("<!a>")),
    row("p <!a b> q", html("<!a b>")),
    row('p <!a "x"> q', html('<!a "x">')),
    row("p <!a>q", html("<!a>")),
    row("p <!a>b", html("<!a>")),
    row("p <!a> q", html("<!a>")),
    row("p <!a> q", html("<!a>")),
    row("p <!a> q", html("<!a>")),
    row("p <!a> q", html("<!a>")),
    row("p <!a> q", html("<!a>")),
    row("a"),
    row("p <!a> q", html("<!a>")),
    row("p <!a> q", html("<!a>")),
    row("Textz.", footnote("z")),
    row("p <!a> q", html("<!a>")),
    row("p <!a\nb> q", html("<!a\nb>")),
    row("p <!A> q", html("<!A>")),
    row("p <!DOCTYPE html> q", html("<!DOCTYPE html>")),
    row("p <!> q"),
    row("p <!1> q"),
    row("p <! a> q"),
    row("p <!a> q"),
    row("p <!a> q"),
  ]);
});

// The row's central claim, held to over the whole table rather than over its own document alone:
// wherever a corpus document wraps emphasis, strong, strikethrough or a link around an inline
// leaf - which `marks-on-footnote-references`, `marks-on-images`, `marks-on-inline-html` and
// `links-holding-an-autolink` do in every shape the two readers argued over - no mark element
// stands between that leaf and its paragraph.
test("no mark element stands between an inline leaf and its paragraph, in any document of the table", () => {
  const wrapped: string[] = [];
  for (const { entry, leaves: paragraphs } of wholeTable()) {
    for (const { leaves } of paragraphs) {
      for (const leaf of leaves) {
        if (leaf.marks.length > 0) {
          wrapped.push(
            `${entry.name}: ${leaf.kind} ${leaf.identity} inside ${leaf.marks.join(", ")}`
          );
        }
      }
    }
  }
  expect(wrapped).toEqual([]);
});

// (c) The claims `indented-code-whitespace-lines.e2e.ts`'s comment row carried, which no paragraph
// reading holds either: the whole text of each `pre code` block, and the `data-spread` of every
// item and every list, in document order. A whitespace-only line indented code keeps is the
// code's, not a blank line, so it spreads neither the list nor the item around the block.

/** What the browser row reads of a drawn body
 *  (`expectEngineReading`, `indented-code-whitespace-lines.e2e.ts:36-53`). */
function codeReading(root: Element): {
  code: string[];
  items: (string | null)[];
  lists: (string | null)[];
} {
  return {
    code: texts(root, "pre code"),
    items: [...root.querySelectorAll("li")].map((item) => item.getAttribute("data-spread")),
    lists: [...root.querySelectorAll("ul, ol")].map((list) => list.getAttribute("data-spread")),
  };
}

test("an indented code block's whitespace lines stay in the block and spread no list or item", () => {
  // This document is the one the surviving browser row reads in a past version
  // (`indented-code-whitespace-lines.e2e.ts:31`), against this same reading: the quoted item's
  // code keeps its inner blank line and drops its trailing ones, the item that holds `x` keeps
  // the line of spaces under it, and only the item whose paragraph and code are parted by a
  // blank line is spread.
  expect(codeReading(draw(fixture("lists-spaced-by-indented-code-whitespace-lines")))).toEqual(
    listsSpacedByIndentedCodeReading
  );
  // No browser row reads this document: the whitespace lines that hold four columns or more past
  // the block's indent stay in it, and the shorter line between them stays too.
  expect(codeReading(draw(fixture("indented-code-trailing-whitespace-lines")))).toEqual({
    code: [
      "      x\n    \n   ",
      "code",
      "code\n",
      "code\n\t",
      "      x\n   \n  ",
      "    x\n  \n ",
      "    x\n  ",
      "    x\n      ",
      "x\n  ",
      "code\n  ",
      "  x\n    \n   ",
      "x",
      "x",
    ],
    items: ["true", "true", "false", "true", "true", "false"],
    lists: ["false", "false", "false", "false", "false", "false"],
  });
  // The edge no browser row holds any more: a block whose last line is whitespace and which ends
  // in no line feed keeps that line.
  expect(
    codeReading(draw(fixture("indented-code-ending-in-a-whitespace-line-with-no-line-feed")))
  ).toEqual({ code: ["code\n"], items: [], lists: [] });
});
