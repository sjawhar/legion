import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";

const output = resolve(import.meta.dir, "../src/dispatch-api.generated.ts");
const generator = resolve(import.meta.dir, "gen-api.ts");
const repoRoot = resolve(import.meta.dir, "../../..");

describe("gen-api", () => {
  // The generator shells out to Biome, so Bun's 5 s default cannot cover a cold CI runner.
  test("the committed client types are what the generator emits", async () => {
    const process = Bun.spawn(["bun", generator, "--check"], {
      cwd: repoRoot,
      stderr: "pipe",
      stdout: "pipe",
    });
    const stderr = await new Response(process.stderr).text();
    const exitCode = await process.exited;

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);

    const source = await Bun.file(output).text();
    expect(source).toContain(
      "// Code generated by scripts/gen-api.ts from schemas/dispatch-openapi.json. DO NOT EDIT."
    );
    expect(source).toContain('export type Issue = components["schemas"]["Issue"];');
  }, 120_000);

  // A hand-edit of the generated file fails CI naming the file it found stale. The hand-edit lands
  // on a copy under GEN_API_CHECK_ROOT, never on the tracked file this workspace shares.
  test(`a hand-edit of ${relative(repoRoot, output)} makes --check fail, naming it`, async () => {
    const root = mkdtempSync(join(tmpdir(), "gen-api-check-"));
    const staleCopy = resolve(root, relative(repoRoot, output));
    try {
      mkdirSync(dirname(staleCopy), { recursive: true });
      await Bun.write(staleCopy, `${await Bun.file(output).text()}// hand-edited\n`);

      const spawned = Bun.spawn(["bun", generator, "--check"], {
        cwd: repoRoot,
        env: { ...process.env, GEN_API_CHECK_ROOT: root },
        stderr: "pipe",
        stdout: "pipe",
      });
      const stderr = await new Response(spawned.stderr).text();
      const exitCode = await spawned.exited;

      expect(exitCode).not.toBe(0);
      expect(stderr).toContain(`${staleCopy} is stale`);
    } finally {
      rmSync(root, { force: true, recursive: true });
    }
  }, 120_000);
});
