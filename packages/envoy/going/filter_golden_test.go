package going

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"testing"
)

var updateGoldens = flag.Bool("update", false, "update golden files")

// filteredAnswersPath is the golden this suite writes and a renderer reads. Every assertion this
// package makes about a link is a proxy: the text of each probe, and a list of marks no answer
// may decode to (noAutolink). A list names the forms it already knows, and a form it does not
// name is what slipped the last two rounds of review, so the ground truth is what the markdown
// engine the Dispatch web app renders with makes of the filter's output. That engine is
// JavaScript, so this file is the join: Go writes what the filter emitted for every probe of the
// suite, and packages/proof-editor/tests/going-answer-no-link.test.ts parses each one with the
// app's own remark pipeline and fails on a link, an image or a raw tag in the tree.
const filteredAnswersPath = "testdata/filtered-answers.json"

// filteredAnswersGenerator is written into the golden itself, because a generated file read from
// another package is one a reader finds without its generator beside it.
const filteredAnswersGenerator = "generated by packages/envoy/going/filter_golden_test.go " +
	"(go test ./going -run TestTheFilteredAnswersAreWhatTheFilterEmits -update); never hand-edited"

// filteredAnswer is one probe of the suite: the name this package knows it by, the answer the
// model wrote, and the whole text of every frame the filter emitted for it - the text a reader is
// given, which is the text a renderer is given.
type filteredAnswer struct {
	Probe    string `json:"probe"`
	Answer   string `json:"answer"`
	Filtered string `json:"filtered"`
}

// filteredAnswers is the whole golden: its own provenance, and every probe in the order this
// package declares them.
type filteredAnswers struct {
	Generator string           `json:"generator"`
	Answers   []filteredAnswer `json:"answers"`
}

// filterOnce is the whole text of every frame a reader gets of one answer. The answer is written
// as one delta: the suite's other tests drive every probe at several delta sizes and assert the
// same text each time, so how the deltas fall is no part of what the golden records.
func filterOnce(t *testing.T, answer string) string {
	t.Helper()
	return drive(t, citationsOf(citedIssue, citedComment), answer).text()
}

// filteredSuite is every probe the suite holds, filtered. The probes are read from allProbes,
// which is the suite's own list, so the golden cannot name a form the suite no longer has or
// miss one it gained.
func filteredSuite(t *testing.T) filteredAnswers {
	t.Helper()
	probes := allProbes()
	suite := filteredAnswers{
		Generator: filteredAnswersGenerator,
		Answers:   make([]filteredAnswer, 0, len(probes)),
	}
	for _, probe := range probes {
		suite.Answers = append(suite.Answers, filteredAnswer{
			Probe:    probe.name,
			Answer:   probe.answer,
			Filtered: filterOnce(t, probe.answer),
		})
	}
	return suite
}

// TestTheFilteredAnswersAreWhatTheFilterEmits: the golden the renderer's test reads is what this
// filter emits today. It fails naming the probe whose text moved, because a renderer's verdict on
// a stale file says nothing about the filter that is in the tree.
func TestTheFilteredAnswersAreWhatTheFilterEmits(t *testing.T) {
	got := filteredSuite(t)
	encoded, err := json.MarshalIndent(got, "", "  ")
	if err != nil {
		t.Fatalf("encode the filtered answers: %v", err)
	}
	encoded = append(encoded, '\n')

	if *updateGoldens {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatalf("create the testdata directory: %v", err)
		}
		if err := os.WriteFile(filteredAnswersPath, encoded, 0o644); err != nil {
			t.Fatalf("write %s: %v", filteredAnswersPath, err)
		}
		return
	}

	goldenBytes, err := os.ReadFile(filteredAnswersPath)
	if err != nil {
		t.Fatalf("read %s (run with -update to write it): %v", filteredAnswersPath, err)
	}
	want := filteredAnswers{}
	if err := json.Unmarshal(goldenBytes, &want); err != nil {
		t.Fatalf("decode %s (run with -update to write it): %v", filteredAnswersPath, err)
	}

	committed := make(map[string]filteredAnswer, len(want.Answers))
	for _, answer := range want.Answers {
		committed[answer.Probe] = answer
	}
	for _, answer := range got.Answers {
		was, held := committed[answer.Probe]
		if !held {
			t.Errorf("%s holds no probe %q: the suite gained it (run with -update to write it)",
				filteredAnswersPath, answer.Probe)
			continue
		}
		delete(committed, answer.Probe)
		if was.Filtered != answer.Filtered {
			t.Errorf("probe %q: the filter emits %q, %s holds %q (run with -update to write it)",
				answer.Probe, answer.Filtered, filteredAnswersPath, was.Filtered)
		}
		if was.Answer != answer.Answer {
			t.Errorf("probe %q: the model's answer is %q, %s holds %q (run with -update to write it)",
				answer.Probe, answer.Answer, filteredAnswersPath, was.Answer)
		}
	}
	for probe := range committed {
		t.Errorf("%s holds the probe %q, which the suite no longer has (run with -update to write it)",
			filteredAnswersPath, probe)
	}

	// The probes agree, so what is left is the file itself: its order, its provenance line and
	// its formatting are what -update writes, and a hand-edited golden is no golden.
	if !bytes.Equal(goldenBytes, encoded) {
		t.Errorf("%s is not what -update writes (run with -update to write it):\ngot:  %s\nwant: %s",
			filteredAnswersPath, goldenBytes, encoded)
	}
}
