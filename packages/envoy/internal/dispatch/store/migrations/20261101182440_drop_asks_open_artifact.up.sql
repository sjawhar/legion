-- 20261101182440_drop_asks_open_artifact.up.sql
-- asks_open_artifact, `asks (artifact_id) where state = 'open' and artifact_id is not null`
-- (0009), was built for the one read that lists a document's open asks
-- (api/asks.go listArtifactAsksQueryOpen). That read uses asks_artifact_id (0032) instead, which
-- api.TestListArtifactAsksOpenQueryUsesAsksArtifactIDIndex holds it to, and the index audit of
-- 2026-10-25 found asks_open_artifact unused from 2026-10-16 to 2026-10-25. An index nothing
-- reads is write cost on every ask that opens, closes or changes its document, and one more
-- plan the planner costs on every read of asks.
-- Dropping it is a contracting change, and the expand-then-contract rule does not hold it to
-- the next release: an index is not a shape the running code reads, so the release before this
-- one and the release after it both keep working over this schema, with one plan choice fewer.
-- `drop index` takes `ACCESS EXCLUSIVE` on asks for the instant it unlinks the index, inside
-- the runner's one transaction, so every read and write of an ask waits behind it for that
-- moment; it reads no row of the table and rewrites none.
drop index asks_open_artifact;
