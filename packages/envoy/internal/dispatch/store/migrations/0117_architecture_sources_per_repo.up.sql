-- 0117_architecture_sources_per_repo.up.sql — a project imports its components from more than one
-- repository.
--
-- An architecture source was one row per project (0036). It becomes one row per repository of a
-- project: id names the source within its project, and a repository is a source of a project at
-- most once, so saving it again changes its branch. Every component records the source that
-- projects it, so one source's import replaces only its own components and deleting a source
-- deletes its components (component_depends follows by its cascade, 0037). Component ids stay
-- project-wide: (project_key, id) is still the components key, which issue attachments, references
-- and the graph_edges view read unchanged.
--
-- Existing rows keep their meaning without a rewrite. id is added with the constant default 0, so
-- every existing source reads 0 from the catalog's missing value; the default is then dropped and
-- the column made an identity starting at 1, so a source added later gets 1, 2, ... and never
-- meets 0. components.source_id is added the same way: every existing component reads 0, its
-- project's one existing source, and the default is dropped so every later write names its
-- source. The foreign key validates every component against a source of its project: only a
-- component written by direct SQL can lack one (the importer writes components under its source's
-- row lock, and the delete route removes them with the source), and the census counts those.
--
-- This is a stop-the-world migration (cmd/dispatch/README.md, "Database migrations"): the earlier
-- release's save upserts on (project_key), which no unique index covers once this commits, and its
-- importer replaces every component of a project from one row. It is deployed with no server of
-- the earlier release running, and a failed deploy recovers forward.
--
-- Both tables are taken in ACCESS EXCLUSIVE first, the source before its components as the
-- importer orders them, since each ALTER below takes that lock anyway and taking them one by one
-- could upgrade a lock a reader already shares.
lock table architecture_sources, components in access exclusive mode;

alter table architecture_sources add column id bigint not null default 0;
alter table architecture_sources alter column id drop default;
alter table architecture_sources alter column id add generated by default as identity (start with 1);
alter table architecture_sources drop constraint architecture_sources_pkey;
alter table architecture_sources add primary key (project_key, id);
create unique index architecture_sources_project_repo on architecture_sources (project_key, repo);

alter table components add column source_id bigint not null default 0;
alter table components alter column source_id drop default;
alter table components add constraint components_source_fkey
  foreign key (project_key, source_id) references architecture_sources (project_key, id) on delete cascade;
