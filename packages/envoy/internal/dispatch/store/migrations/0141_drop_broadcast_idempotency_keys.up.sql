-- 0141_drop_broadcast_idempotency_keys.up.sql
-- INFRA-258: the contracting half of 0137_request_keys. broadcast_idempotency_keys (0055) held the
-- key of each broadcast a person sent before every write took an Idempotency-Key header; since
-- 0137's release a broadcast's key is a request_keys row, and no server of that release or any
-- later one reads or writes this table. 0137 kept it so a deploy of that release could roll back
-- to the one before; this drop ships in a later release, as the expand-then-contract rule in
-- cmd/dispatch/README.md ("Database migrations") requires, and ends that rollback path.
--
-- Dropping it takes ACCESS EXCLUSIVE on broadcasts as well as on the table itself, since the
-- table's foreign key puts triggers on broadcasts (measured on PostgreSQL 16: the lock is the same
-- whether the constraint is dropped first or with the table). It reads no row, so it holds that
-- lock for the instant the migration's transaction lasts, and pgmigrate.LockTimeout bounds the
-- wait for it: a broadcast read or send waits that instant.
drop table broadcast_idempotency_keys;
